/*********************************************************************************************************************
* 文件名称          line_follow
* 功能描述          智能车摄像头扫描巡线 - 巡线主控模块头文件
* 适用平台          MM32F327X_G8P
* 说明              巡线模块是图像处理算法的上层封装
*                   负责协调摄像头图像采集与图像处理的时序
*                   并将处理结果（中线数据）提供给后续的PID控制模块使用
*
* 工作流程：
*   摄像头采集一帧图像 → 图像处理管线 → 得到中线数组 →
*   中线数据可供舵机PID和电机PID使用（后续步骤不在此代码范围内）
*
* 注意：此文件只包含巡线相关的内容
*       舵机PID控制和电机PID控制的具体实现在后续步骤中完成
*       本代码到"中线数组存储完毕"为止
*********************************************************************************************************************/

#ifndef _line_follow_h_
#define _line_follow_h_

#include "zf_common_headfile.h"
#include "image_process.h"
#include "common_Mymenu.h"

//==================================================== 直道检测配置 ====================================================

#define STRAIGHT_DETECT_ROW       (2)                                             // 直道检测行号

//==================================================== 巡线状态定义 ====================================================

// 巡线工作状态枚举
typedef enum
{
    LINE_STATE_IDLE,                                                            // 空闲状态（未开始巡线）
    LINE_STATE_WAIT_IMAGE,                                                      // 等待图像采集完成
    LINE_STATE_PROCESSING,                                                      // 正在处理图像
    LINE_STATE_DONE,                                                            // 图像处理完成，中线数据可用
}line_follow_state_enum;

//==================================================== 外部变量声明 ====================================================







extern line_follow_state_enum line_state;                                       // 巡线当前工作状态
extern uint8 line_data_ready;                                                   // 中线数据就绪标志（1=可被PID控制模块读取）


extern float image_pid_error;                                                   //图像环的误差，可供动态变速使用


//==================================================== 函数声明 ====================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     巡线模块初始化
// 参数说明     void
// 返回参数     void
// 使用示例     line_follow_init();
// 备注信息     在 main() 初始化阶段调用，设置巡线模块的初始状态
//-------------------------------------------------------------------------------------------------------------------
void line_follow_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     巡线主处理函数（每帧调用一次）
// 参数说明     void
// 返回参数     void
// 使用示例     在主循环 while(1) 中调用 line_follow_process();
// 备注信息     内部会检测 mt9v03x_finish_flag 标志
//              当一帧图像采集完成后自动触发图像处理管线
//              处理完成后将 line_data_ready 置1
//-------------------------------------------------------------------------------------------------------------------
void line_follow_process(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取指定行的赛道中线X坐标
// 参数说明     row —— 行号（0 ~ IMG_H-1）
// 返回参数     uint8 —— 该行的中线X坐标（0 ~ IMG_W-1）
// 使用示例     uint8 mid_x = get_center_line(89);  // 获取最底行的中线
// 备注信息     row 参数会被限幅到有效范围
//              如果中线数据尚未就绪（line_data_ready==0），返回图像中心值 IMG_W/2
//-------------------------------------------------------------------------------------------------------------------
uint8 get_center_line(uint8 row);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取指定行的左边界X坐标
// 参数说明     row —— 行号（0 ~ IMG_H-1）
// 返回参数     uint8 —— 该行的左边界X坐标
// 使用示例     uint8 left_x = get_left_boundary(89);
// 备注信息     如果边界数据尚未就绪，返回0
//-------------------------------------------------------------------------------------------------------------------
uint8 get_left_boundary(uint8 row);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取指定行的右边界X坐标
// 参数说明     row —— 行号（0 ~ IMG_H-1）
// 返回参数     uint8 —— 该行的右边界X坐标
// 使用示例     uint8 right_x = get_right_boundary(89);
// 备注信息     如果边界数据尚未就绪，返回 IMG_W-1
//-------------------------------------------------------------------------------------------------------------------
uint8 get_right_boundary(uint8 row);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取当前二值化阈值
// 参数说明     void
// 返回参数     uint8 —— 当前使用的二值化阈值
// 使用示例     uint8 thresh = get_current_threshold();
// 备注信息     可用于调试或显示当前的阈值
//-------------------------------------------------------------------------------------------------------------------
uint8 get_current_threshold(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     计算车身偏差（横向偏移量）
// 参数说明     look_ahead_rows —— 前瞻行数（从底部向上偏移的行数，0表示看最底行）
// 返回参数     int16 —— 偏差值（正值=中线偏右/车偏左，负值=中线偏左/车偏右）
// 使用示例     int16 error = calc_deviation(15);  // 前瞻15行
// 备注信息     偏差 = 前瞻行的中线X坐标 - 图像中心X坐标(IMG_W/2=70)
//              正值：中线在图像中心右侧 → 车身偏向赛道左侧 → 需要向右修正
//              负值：中线在图像中心左侧 → 车身偏向赛道右侧 → 需要向左修正
//-------------------------------------------------------------------------------------------------------------------
int16 calc_deviation(uint8 look_ahead_rows);


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     直道/弯道判别（封装为统一函数，image内外共用）
// 参数说明     void
// 返回参数     uint8 —— 1=直道, 0=弯道
// 使用示例     uint8 is_straight = is_straight_detect();
// 备注信息     基于 STRAIGHT_DETECT_ROW 行的白点+边界位置判断
//-------------------------------------------------------------------------------------------------------------------
uint8 is_straight_detect(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取中线的加权位置（用于PID控制）
// 参数说明     center_line —— 中线数组指针（长度为 IMG_H）
// 返回参数     float —— 加权位置（0~IMG_W-1）
// 使用示例     float weight_pos = get_weight_position(center_line, is_straight);
// 备注信息     直道用weight[]（中间权重大），弯道用weight2[]（近端权重大）
//-------------------------------------------------------------------------------------------------------------------
float get_weight_position(uint8 *center_line, uint8 is_straight);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     丢线边界补偿（单侧丢线>9/10时，对侧边界向内偏移10px）
// 参数说明     void
// 返回参数     void
// 使用示例     boundary_lost_compensate();
// 备注信息     统计行10~IMG_H-1
//              左丢→右边界左移10px，右丢→左边界右移10px，双侧都丢→不偏移
//-------------------------------------------------------------------------------------------------------------------
void boundary_lost_compensate(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     pid计算图像输出值
// 参数说明     target —— 目标值（期望位置）
// 参数说明     actual —— 实际值（当前偏差）
// 返回参数     float —— 舵机输出值（用于控制舵机转角）
// 使用示例     float image_output = image_pid_set(target, actual);
// 备注信息     使用PID算法计算舵机的控制输出
//              其中 target 是期望位置，actual 是当前偏差
//              输出值可用于角速度以纠正偏差
//-------------------------------------------------------------------------------------------------------------------
float image_pid_set(float target,float actual);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     IMU角速度闭环PID（陀螺仪→舵机打角）
// 参数说明     target —— 目标角速度（来自图像PID）
// 参数说明     actual —— 实际角速度（陀螺仪Z轴）
// 返回参数     float —— 舵机角度
//-------------------------------------------------------------------------------------------------------------------
float IMU_pid_set(float target,float actual);


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     pid计算电机差速输出值
// 参数说明     target —— 目标值（期望位置）
// 参数说明     actual —— 实际值（当前偏差）
// 返回参数     float —— 电机差速输出值（用于控制电机差速差速）
// 使用示例     float motor_output = motor_pid_set(target, actual);
// 备注信息     使用PID算法计算电机差速的控制输出
//              其中 target 是期望位置，actual 是当前偏差
//              输出值可用于调整电机差速以纠正偏差
//-------------------------------------------------------------------------------------------------------------------

float motor_pid_set(float target,float actual);

//==================================================== 姿态解算（六轴互补滤波） ====================================================

// 角度 PID 参数（蓝牙可调）
extern float angle_kp_a;
extern float angle_kp_b;
extern float angle_kd;
extern float angle_lowpass;

// 姿态解算输出（当前偏航角，°）
extern float atti_yaw;

// 融合系数：final_servo = α × angle_pid_out + (1-α) × IMU_pid_out
extern float servo_fusion_alpha;

// 上一帧舵机角度：用于小角度时不启用 kp_b 非线性项
extern float prev_servo_angle;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     姿态解算初始化（六轴互补滤波 AHRS）
//-------------------------------------------------------------------------------------------------------------------
void atti_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     姿态解算更新（在 PIT 中断中调用，5ms 周期）
// 参数说明     void
// 返回参数     void
// 备注信息     读取加速度计+陀螺仪，互补滤波更新四元数，提取 Yaw
//-------------------------------------------------------------------------------------------------------------------
void atti_update(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     角度 PID（偏航角稳定控制）
// 参数说明     target —— 目标角度（上一次的偏航角，°）
// 参数说明     actual —— 实际角度（当前的偏航角，°）
// 返回参数     float —— 舵机角度（左=负，右=正）
// 备注信息     与 IMU_pid_set 输出融合后作为最终舵角
//-------------------------------------------------------------------------------------------------------------------
float angle_pid_set(float target, float actual);

//-------------------------------------------------------------------------------------------------------------------
// speed_pid_set
// 功能：速度 PID
// 参数：target —— 目标速度
// 参数：actual —— 实际速度
// 返回：float —— 电机占空比
//
//-------------------------------------------------------------------------------------------------------------------
float speed_pid_set(uint8 channel, float target, float actual);


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     融合角度 PID 和 IMU PID 的输出
// 参数说明     angle_out —— 角度 PID 输出（°）
// 参数说明     IMU_out   —— IMU PID 输出（°）
// 返回参数     float —— 融合后的舵机角度（左=负，右=正）
//-------------------------------------------------------------------------------------------------------------------
float servo_fusion(float angle_out, float IMU_out);

#endif
